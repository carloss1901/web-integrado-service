/* Índices compuestos para filtros, SLA, rankings y carga operativa. */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INCIDENCIA_SLA_ACTIVO_ESTADO_LIMITE')
    CREATE INDEX IX_INCIDENCIA_SLA_ACTIVO_ESTADO_LIMITE
        ON INCIDENCIA (ACTIVO, ID_ESTADO, FECHA_LIMITE)
        INCLUDE (ID_SEVERIDAD, ID_RESPONSABLE, ID_CATEGORIA, ID_UBICACION);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INCIDENCIA_RESPONSABLE_ACTIVO_ESTADO')
    CREATE INDEX IX_INCIDENCIA_RESPONSABLE_ACTIVO_ESTADO
        ON INCIDENCIA (ID_RESPONSABLE, ACTIVO, ID_ESTADO, FECHA_REGISTRO);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INCIDENCIA_CATEGORIA_UBICACION_FECHA')
    CREATE INDEX IX_INCIDENCIA_CATEGORIA_UBICACION_FECHA
        ON INCIDENCIA (ID_CATEGORIA, ID_UBICACION, FECHA_REGISTRO)
        INCLUDE (ID_SEVERIDAD, ID_ESTADO);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_INCIDENCIA_SEVERIDAD_FECHA')
    CREATE INDEX IX_INCIDENCIA_SEVERIDAD_FECHA
        ON INCIDENCIA (ID_SEVERIDAD, FECHA_REGISTRO)
        INCLUDE (ID_ESTADO, ID_RESPONSABLE, FECHA_LIMITE);
GO
