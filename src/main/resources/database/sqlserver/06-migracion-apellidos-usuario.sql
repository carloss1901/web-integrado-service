/*
    CampusSeguro 360
    Migración de APELLIDOS a APE_PATERNO y APE_MATERNO.

    Conserva el valor existente de APELLIDOS como apellido paterno.
    Ejecutar una sola vez en bases creadas con la estructura anterior.
*/

USE CAMPUSSEGURO360;
GO

SET XACT_ABORT ON;

IF COL_LENGTH('USUARIO', 'APE_PATERNO') IS NULL
    ALTER TABLE USUARIO ADD APE_PATERNO VARCHAR(100) NULL;
GO

IF COL_LENGTH('USUARIO', 'APE_MATERNO') IS NULL
    ALTER TABLE USUARIO ADD APE_MATERNO VARCHAR(100) NULL;
GO

IF COL_LENGTH('USUARIO', 'APELLIDOS') IS NOT NULL
    UPDATE USUARIO
    SET APE_PATERNO = APELLIDOS
    WHERE APE_PATERNO IS NULL OR LTRIM(RTRIM(APE_PATERNO)) = '';
GO

IF EXISTS (SELECT 1 FROM USUARIO WHERE APE_PATERNO IS NULL OR LTRIM(RTRIM(APE_PATERNO)) = '')
    THROW 50001, 'No se puede migrar USUARIO: existen registros sin apellido paterno.', 1;
GO

ALTER TABLE USUARIO ALTER COLUMN APE_PATERNO VARCHAR(100) NOT NULL;
GO

IF COL_LENGTH('USUARIO', 'APELLIDOS') IS NOT NULL
    ALTER TABLE USUARIO DROP COLUMN APELLIDOS;
GO

PRINT 'Migración de apellidos de usuario completada correctamente.';
