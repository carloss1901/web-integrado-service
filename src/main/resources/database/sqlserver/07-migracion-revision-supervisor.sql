IF OBJECT_ID('INCIDENCIA_REVISION_SUPERVISOR', 'U') IS NULL
BEGIN
    CREATE TABLE INCIDENCIA_REVISION_SUPERVISOR (
        ID_REVISION INT IDENTITY(1,1) NOT NULL,
        ID_INCIDENCIA INT NOT NULL,
        ID_SUPERVISOR INT NOT NULL,
        APROBADA BIT NOT NULL,
        OBSERVACION NVARCHAR(1000) NOT NULL,
        FECHA_REVISION DATETIME2 NOT NULL,
        ACTIVO BIT NOT NULL CONSTRAINT DF_REVISION_SUPERVISOR_ACTIVO DEFAULT 1,
        FEC_REG DATETIME2 NOT NULL CONSTRAINT DF_REVISION_SUPERVISOR_FEC_REG DEFAULT SYSDATETIME(),
        FEC_MOD DATETIME2 NULL,
        CONSTRAINT PK_INCIDENCIA_REVISION_SUPERVISOR PRIMARY KEY (ID_REVISION),
        CONSTRAINT FK_REVISION_SUPERVISOR_INCIDENCIA FOREIGN KEY (ID_INCIDENCIA) REFERENCES INCIDENCIA (ID_INCIDENCIA),
        CONSTRAINT FK_REVISION_SUPERVISOR_USUARIO FOREIGN KEY (ID_SUPERVISOR) REFERENCES USUARIO (ID_USUARIO)
    );
    CREATE INDEX IX_REVISION_SUPERVISOR_INCIDENCIA_FECHA ON INCIDENCIA_REVISION_SUPERVISOR (ID_INCIDENCIA, FECHA_REVISION DESC);
END;
