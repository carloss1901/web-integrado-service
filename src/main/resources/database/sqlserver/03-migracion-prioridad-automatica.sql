/* RF-03: prioridad calculada automáticamente. Ejecutar una sola vez por base de datos. */
/* CK_PRIORIDAD_RANGO depende de PUNTAJE_MINIMO y PUNTAJE_MAXIMO. */
IF OBJECT_ID('CK_PRIORIDAD_RANGO', 'C') IS NOT NULL
    ALTER TABLE PRIORIDAD DROP CONSTRAINT CK_PRIORIDAD_RANGO;
GO

IF COL_LENGTH('INCIDENCIA', 'PUNTAJE_PRIORIDAD') IS NOT NULL
    ALTER TABLE INCIDENCIA ALTER COLUMN PUNTAJE_PRIORIDAD DECIMAL(4,2) NULL;
GO

IF COL_LENGTH('PRIORIDAD', 'PUNTAJE_MINIMO') IS NOT NULL
    ALTER TABLE PRIORIDAD ALTER COLUMN PUNTAJE_MINIMO DECIMAL(4,2) NOT NULL;
IF COL_LENGTH('PRIORIDAD', 'PUNTAJE_MAXIMO') IS NOT NULL
    ALTER TABLE PRIORIDAD ALTER COLUMN PUNTAJE_MAXIMO DECIMAL(4,2) NOT NULL;
GO

IF COL_LENGTH('INCIDENCIA_HISTORIAL', 'IMPACTO') IS NULL
    ALTER TABLE INCIDENCIA_HISTORIAL ADD IMPACTO INT NULL;
IF COL_LENGTH('INCIDENCIA_HISTORIAL', 'URGENCIA') IS NULL
    ALTER TABLE INCIDENCIA_HISTORIAL ADD URGENCIA INT NULL;
IF COL_LENGTH('INCIDENCIA_HISTORIAL', 'REINCIDENCIA') IS NULL
    ALTER TABLE INCIDENCIA_HISTORIAL ADD REINCIDENCIA INT NULL;
IF COL_LENGTH('INCIDENCIA_HISTORIAL', 'PUNTAJE_PRIORIDAD') IS NULL
    ALTER TABLE INCIDENCIA_HISTORIAL ADD PUNTAJE_PRIORIDAD DECIMAL(4,2) NULL;
GO

IF COL_LENGTH('INCIDENCIA', 'IMPACTO') IS NOT NULL
    ALTER TABLE INCIDENCIA DROP CONSTRAINT IF EXISTS CK_INCIDENCIA_IMPACTO;
IF COL_LENGTH('INCIDENCIA', 'URGENCIA') IS NOT NULL
    ALTER TABLE INCIDENCIA DROP CONSTRAINT IF EXISTS CK_INCIDENCIA_URGENCIA;
IF COL_LENGTH('INCIDENCIA', 'REINCIDENCIA') IS NOT NULL
    ALTER TABLE INCIDENCIA DROP CONSTRAINT IF EXISTS CK_INCIDENCIA_REINCIDENCIA;
GO

ALTER TABLE INCIDENCIA ADD CONSTRAINT CK_INCIDENCIA_IMPACTO
    CHECK (IMPACTO IS NULL OR IMPACTO BETWEEN 1 AND 4);
ALTER TABLE INCIDENCIA ADD CONSTRAINT CK_INCIDENCIA_URGENCIA
    CHECK (URGENCIA IS NULL OR URGENCIA BETWEEN 1 AND 4);
ALTER TABLE INCIDENCIA ADD CONSTRAINT CK_INCIDENCIA_REINCIDENCIA
    CHECK (REINCIDENCIA IS NULL OR REINCIDENCIA BETWEEN 1 AND 4);
GO

UPDATE PRIORIDAD SET PUNTAJE_MINIMO = 1.00, PUNTAJE_MAXIMO = 1.75 WHERE NOMBRE = 'BAJA';
UPDATE PRIORIDAD SET PUNTAJE_MINIMO = 1.75, PUNTAJE_MAXIMO = 2.50 WHERE NOMBRE = 'MEDIA';
UPDATE PRIORIDAD SET PUNTAJE_MINIMO = 2.50, PUNTAJE_MAXIMO = 3.25 WHERE NOMBRE = 'ALTA';
UPDATE PRIORIDAD SET PUNTAJE_MINIMO = 3.25, PUNTAJE_MAXIMO = 4.00 WHERE NOMBRE = 'CRITICA';
GO

IF OBJECT_ID('CK_PRIORIDAD_RANGO', 'C') IS NULL
    ALTER TABLE PRIORIDAD ADD CONSTRAINT CK_PRIORIDAD_RANGO
        CHECK (PUNTAJE_MINIMO <= PUNTAJE_MAXIMO);
GO

