/*
    CampusSeguro 360
    Limpieza total de datos para SQL Server.

    ADVERTENCIA:
    - Elimina todos los registros de las tablas del sistema.
    - Conserva la estructura, restricciones e índices.
    - Reinicia las columnas IDENTITY para que vuelvan a iniciar en 1.
    - Ejecutar únicamente en ambientes de desarrollo o prueba.
*/

USE CAMPUSSEGURO360;
GO

SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRANSACTION;

    /* Tablas hijas de INCIDENCIA */
    DELETE FROM INCIDENCIA_EVIDENCIA;
    DELETE FROM INCIDENCIA_ACCION_CORRECTIVA;
    DELETE FROM INCIDENCIA_COMENTARIO;
    DELETE FROM INCIDENCIA_HISTORIAL;

    /* Tabla transaccional principal */
    DELETE FROM INCIDENCIA;

    /* Catálogos y relaciones de usuarios */
    DELETE FROM SLA;
    DELETE FROM USUARIO_ROL;
    DELETE FROM CATEGORIA;
    DELETE FROM UBICACION;
    DELETE FROM SEVERIDAD;
    DELETE FROM PRIORIDAD;
    DELETE FROM ESTADO_INCIDENCIA;
    DELETE FROM USUARIO;
    DELETE FROM ROL;

    /* Reinicio de identidades */
    DBCC CHECKIDENT ('INCIDENCIA_EVIDENCIA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('INCIDENCIA_ACCION_CORRECTIVA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('INCIDENCIA_COMENTARIO', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('INCIDENCIA_HISTORIAL', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('INCIDENCIA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('SLA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('USUARIO_ROL', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('CATEGORIA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('UBICACION', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('SEVERIDAD', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('PRIORIDAD', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('ESTADO_INCIDENCIA', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('USUARIO', RESEED, 0) WITH NO_INFOMSGS;
    DBCC CHECKIDENT ('ROL', RESEED, 0) WITH NO_INFOMSGS;

    COMMIT TRANSACTION;
    PRINT 'Limpieza de datos completada correctamente.';
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0
        ROLLBACK TRANSACTION;

    THROW;
END CATCH;
GO
