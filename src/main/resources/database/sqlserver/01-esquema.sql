CREATE TABLE INCIDENCIA (
    ID_INCIDENCIA INT IDENTITY(1,1) NOT NULL,
    CODIGO VARCHAR(50) NOT NULL,
    ID_REPORTANTE INT NOT NULL,
    ID_RESPONSABLE INT NULL,
    ID_CATEGORIA INT NOT NULL,
    ID_UBICACION INT NOT NULL,
    ID_SEVERIDAD INT NULL,
    ID_PRIORIDAD INT NULL,
    ID_ESTADO INT NOT NULL,
    ID_SLA INT NULL,
    IMPACTO INT NULL,
    URGENCIA INT NULL,
    REINCIDENCIA INT NULL,
    PUNTAJE_PRIORIDAD INT NULL,
    TITULO VARCHAR(200) NOT NULL,
    DESCRIPCION NVARCHAR(MAX) NOT NULL,
    FECHA_REGISTRO DATETIME2 NOT NULL,
    FECHA_LIMITE DATETIME2 NULL,
    FECHA_RESOLUCION DATETIME2 NULL,
    FECHA_CIERRE DATETIME2 NULL,
    ACTIVO BIT NOT NULL
        CONSTRAINT DF_INCIDENCIA_ACTIVO DEFAULT 1,
    FEC_REG DATETIME2 NOT NULL
        CONSTRAINT DF_INCIDENCIA_FEC_REG DEFAULT SYSDATETIME(),
    FEC_MOD DATETIME2 NULL,

    CONSTRAINT PK_INCIDENCIA PRIMARY KEY (ID_INCIDENCIA),
    CONSTRAINT UK_INCIDENCIA_CODIGO UNIQUE (CODIGO),

    CONSTRAINT CK_INCIDENCIA_IMPACTO
        CHECK (IMPACTO IS NULL OR IMPACTO IN (1, 2, 3)),

    CONSTRAINT CK_INCIDENCIA_URGENCIA
        CHECK (URGENCIA IS NULL OR URGENCIA IN (1, 2, 3)),

    CONSTRAINT CK_INCIDENCIA_REINCIDENCIA
        CHECK (REINCIDENCIA IS NULL OR REINCIDENCIA IN (0, 1)),

    CONSTRAINT FK_INCIDENCIA_REPORTANTE
        FOREIGN KEY (ID_REPORTANTE)
        REFERENCES USUARIO (ID_USUARIO),

    CONSTRAINT FK_INCIDENCIA_RESPONSABLE
        FOREIGN KEY (ID_RESPONSABLE)
        REFERENCES USUARIO (ID_USUARIO),

    CONSTRAINT FK_INCIDENCIA_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA (ID_CATEGORIA),

    CONSTRAINT FK_INCIDENCIA_UBICACION
        FOREIGN KEY (ID_UBICACION)
        REFERENCES UBICACION (ID_UBICACION),

    CONSTRAINT FK_INCIDENCIA_SEVERIDAD
        FOREIGN KEY (ID_SEVERIDAD)
        REFERENCES SEVERIDAD (ID_SEVERIDAD),

    CONSTRAINT FK_INCIDENCIA_PRIORIDAD
        FOREIGN KEY (ID_PRIORIDAD)
        REFERENCES PRIORIDAD (ID_PRIORIDAD),

    CONSTRAINT FK_INCIDENCIA_ESTADO
        FOREIGN KEY (ID_ESTADO)
        REFERENCES ESTADO_INCIDENCIA (ID_ESTADO),

    CONSTRAINT FK_INCIDENCIA_SLA
        FOREIGN KEY (ID_SLA)
        REFERENCES SLA (ID_SLA)
);
GO

